## AFF：你的独立跳伞之路

### 什么是AFF？

AFF（加速自由落体）是一个结构化的训练课程，教你独立跳伞。通过7-8个渐进级别，你将学习从身体姿势和自由落体控制到降落伞打开和着陆的一切。

### 课程结构

| 级别 | 你会学到什么 |
|------|------------|
| **第1-3级** | 基本身体姿势、高度意识、练习拉伞 |
| **第4-5级** | 转弯、前进移动、独立稳定 |
| **第6-7级** | 后空翻、追踪飞行、进阶动作 |
| **第8级+** | 独立跳伞、巩固练习、考试准备 |

每个级别包括地面简报、与教练的一次跳伞和回顾。当教练确认你的技能后，你就可以进入下一级。

### AFF套餐通常包含什么

- 综合地面课程（第一天4-6小时）
- 每次跳伞的所有装备
- 监督跳伞的教练费用
- 跳伞日志和进度卡
- 通往A牌照认证之路

### 适合谁？

- ✅ 任何梦想独立跳伞的人
- ✅ 想要更深入、基于技能体验的刺激寻求者
- ✅ 未来的运动跳伞员、翼装飞行者或编队跳伞者
- ✅ 喜欢学习和掌握新技能的人

### 时间投入

- **地面课程**：1整天
- **第1-8级**：通常8-15个跳伞日，分布在数周或数月（取决于天气）
- **到A牌照的总跳伞次数**：通常25次以上，包括巩固练习

